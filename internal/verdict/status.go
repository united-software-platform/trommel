// Пакет verdict описывает вердикт Trommel: состояние каждого правила состава
// и границу того, о чём вердикт ничего не утверждает.
//
// Вердикт — единственный продукт Trommel. Блокирование остаётся за вызывающей
// стороной, поэтому вердикту важно быть не кратким, а полным: «соблюдено»
// и «не проверялось» обязаны быть разными ответами.
package verdict

// Status — состояние правила в прогоне.
type Status string

const (
	// StatusOK — правило проверено полностью и соблюдается.
	StatusOK Status = "ok"
	// StatusFail — правило проверено, нарушения найдены.
	StatusFail Status = "fail"
	// StatusErr — проверка не состоялась: содержимое не разобрано, конструкция
	// не опознана или реализация не уверена. Для вызывающей стороны это отказ
	// отвечать, а не чистота.
	StatusErr Status = "err"
	// StatusSkip — правило к этому проекту неприменимо.
	StatusSkip Status = "skip"
	// StatusNone — реализации нет; Trommel об этом правиле ничего не утверждает.
	StatusNone Status = "--"
)

// Проверено отвечает, означает ли состояние выполненную проверку. Только такие
// состояния входят в число проверенных правил при подсчёте знаменателя.
func (s Status) Проверено() bool {
	return s == StatusOK || s == StatusFail
}

// String даёт представление состояния для вывода.
func (s Status) String() string { return string(s) }
